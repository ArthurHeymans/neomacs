use std::time::Duration;

use crate::{ADD_NODE_MODULES_PATH_MELPA_PIN, CachedMelpaOracle};
use expect_test::Expect;

mod command;
mod customization;
mod helpers;
mod registry;

const ADD_NODE_MODULES_PATH_TEST_TIMEOUT: Duration = Duration::from_secs(120);

fn add_node_modules_path_oracle(source_file: &str) -> CachedMelpaOracle {
    CachedMelpaOracle::new(ADD_NODE_MODULES_PATH_MELPA_PIN, source_file)
        .expect("prepare pinned add-node-modules-path source below ./tmp")
        .with_timeout(ADD_NODE_MODULES_PATH_TEST_TIMEOUT)
}

fn current_test_name() -> String {
    let thread = std::thread::current();
    thread
        .name()
        .unwrap_or("unnamed add-node-modules-path parity test")
        .into()
}

fn assert_add_node_modules_path_source_parity(
    source_file: &str,
    elisp_form: &str,
    expected: Expect,
) {
    let name = current_test_name();
    let report = add_node_modules_path_oracle(source_file)
        .run_value(&name, elisp_form)
        .unwrap_or_else(|error| {
            panic!("add-node-modules-path parity case `{name}` failed:\n{error}")
        });
    expected.assert_eq(&report.gnu_emacs.to_string());
}

pub(crate) fn assert_add_node_modules_path_parity(elisp_form: &str, expected: Expect) {
    assert_add_node_modules_path_source_parity("add-node-modules-path.el", elisp_form, expected);
}

pub(crate) fn assert_add_node_modules_path_autoload_parity(elisp_form: &str, expected: Expect) {
    assert_add_node_modules_path_source_parity(
        "add-node-modules-path-autoloads.el",
        elisp_form,
        expected,
    );
}
