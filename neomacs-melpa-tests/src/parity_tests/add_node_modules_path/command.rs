#[test]
fn add_node_modules_path_debug_reports_exact_success_message_and_failure_warnings() {
    let elisp_form = r##"(let ((original-default
                (default-value
                 'exec-path))
               messages
               warnings)
         (unwind-protect
             (progn
               (set-default
                'exec-path
                '("/base"))
               (with-temp-buffer
                 (setq-local
                  add-node-modules-path-command
                  '("one" "bad" "two"))
                 (setq-local
                  add-node-modules-path-debug
                  t)
                 (cl-letf (((symbol-function
                             'shell-command-to-string)
                            (lambda (command)
                              (cdr
                               (assoc
                                command
                                '(("one" . "/one\n")
                                  ("bad" . "failure output\n")
                                  ("two" . "/two\n"))))))
                           ((symbol-function
                             'file-directory-p)
                            (lambda (path)
                              (member
                               path
                               '("/one" "/two"))))
                           ((symbol-function
                             'message)
                            (lambda (format-string &rest arguments)
                              (push
                               (apply
                                #'format
                                format-string
                                arguments)
                               messages)))
                           ((symbol-function
                             'display-warning)
                            (lambda
                              (type message &optional level buffer-name)
                              (push
                               (list
                                type
                                message
                                level
                                buffer-name)
                               warnings))))
                   (let ((return
                          (add-node-modules-path)))
                     (list
                      return
                      exec-path
                      (nreverse
                       messages)
                      (nreverse
                       warnings))))))
           (set-default
            'exec-path
            original-default)))"##;
    let expect = expect![[
        r#"OK (nil ("/one" "/two" "/base") ("Added to `exec-path`: /one, /two") ((add-node-modules-path "Failed to run ‘bad’:\n failure output" nil nil)))"#
    ]];
    assert_add_node_modules_path_parity(elisp_form, expect);
}

