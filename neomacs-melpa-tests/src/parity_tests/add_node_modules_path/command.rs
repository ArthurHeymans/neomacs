#[test]
fn add_node_modules_path_orchestrates_helpers_with_exact_intermediate_values() {
    let elisp_form = r##"(let (calls)
         (with-temp-buffer
           (setq-local
            add-node-modules-path-command
            '(" raw "))
           (setq-local
            add-node-modules-path-debug
            t)
           (cl-letf (((symbol-function
                       'add-node-modules-path/trim-list-and-elements)
                      (lambda (commands)
                        (push
                         (list
                          'trim
                          commands)
                         calls)
                        '("trimmed")))
                     ((symbol-function
                       'add-node-modules-path/exec-command-list)
                      (lambda (commands)
                        (push
                         (list
                          'execute
                          commands)
                         calls)
                        '((command "trimmed" result "/valid" directory-p t)
                          (command "bad" result "failed" directory-p nil))))
                     ((symbol-function
                       'add-node-modules-path/get-valid-directories)
                      (lambda (executions)
                        (push
                         (list
                          'valid
                          executions)
                         calls)
                        nil))
                     ((symbol-function
                       'add-node-modules-path/warn-about-failed-executions)
                      (lambda (executions)
                        (push
                         (list
                          'warn
                          executions)
                         calls)
                        'warned)))
             (let ((return
                    (add-node-modules-path)))
               (list
                return
                (nreverse
                 calls)
                (local-variable-p
                 'exec-path))))))"##;
    let expect = expect![[
        r#"OK (warned ((trim (" raw ")) (execute ("trimmed")) (valid #1=((command "trimmed" result "/valid" directory-p t) (command "bad" result "failed" directory-p nil))) (warn #1#)) nil)"#
    ]];
    assert_add_node_modules_path_parity(elisp_form, expect);
}

