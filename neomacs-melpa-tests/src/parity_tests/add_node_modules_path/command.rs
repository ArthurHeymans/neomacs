use expect_test::expect;

use super::assert_add_node_modules_path_parity;

#[test]
fn add_node_modules_path_command_adds_only_valid_directories_in_command_order() {
    let elisp_form = r##"(let ((original-default
                (default-value
                 'exec-path))
               shell-calls
               directory-calls)
         (unwind-protect
             (progn
               (set-default
                'exec-path
                '("/base" "/shared"))
               (with-temp-buffer
                 (kill-local-variable
                  'exec-path)
                 (setq-local
                  add-node-modules-path-command
                  '(" first "
                    "bad"
                    nil
                    ""
                    "second"))
                 (setq-local
                  add-node-modules-path-debug
                  nil)
                 (cl-letf (((symbol-function
                             'shell-command-to-string)
                            (lambda (command)
                              (push
                               command
                               shell-calls)
                              (cdr
                               (assoc
                                command
                                '(("first" . "/project/a/.bin\n")
                                  ("bad" . "not-a-directory\n")
                                  ("second" . "/project/b/.bin\n"))))))
                           ((symbol-function
                             'file-directory-p)
                            (lambda (path)
                              (push
                               path
                               directory-calls)
                              (member
                               path
                               '("/project/a/.bin"
                                 "/project/b/.bin")))))
                   (let ((return
                          (add-node-modules-path)))
                     (list
                      return
                      (local-variable-p
                       'exec-path)
                      exec-path
                      (default-value
                       'exec-path)
                      (nreverse
                       shell-calls)
                      (nreverse
                       directory-calls))))))
           (set-default
            'exec-path
            original-default)))"##;
    let expect = expect![[
        r#"OK (nil t ("/project/a/.bin" "/project/b/.bin" . #1=("/base" "/shared")) #1# ("first" "bad" "second") ("/project/a/.bin" "not-a-directory" "/project/b/.bin"))"#
    ]];
    assert_add_node_modules_path_parity(elisp_form, expect);
}

