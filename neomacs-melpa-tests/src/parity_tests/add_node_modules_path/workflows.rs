/// The package's headline workflow, from the README: a developer opens a file
/// in a node project whose `eslint' is installed locally and runs
/// `M-x add-node-modules-path'.  Before the command the project's linter cannot
/// be reached at all; after it `executable-find' and `call-process' both reach
/// exactly that project's copy, the editor's own `exec-path' is still intact
/// underneath, and the change is confined to this buffer -- a second buffer
/// visiting a file outside the project still cannot run `eslint', and switching
/// back finds the project path again.
///
/// The recorded tool log is what proves the shell command ran in the visited
/// file's directory rather than in the editor's working directory.
#[test]
fn running_the_command_in_a_project_buffer_puts_that_projects_eslint_on_exec_path() {
    let elisp_form = r##"(progn
  (anmp-install-tools)
  (let* ((project (anmp-project
                   "solo-app"
                   "{\n  \"name\": \"solo-app\",\n  \"version\": \"1.4.0\"\n}\n"
                   '("eslint" . "eslint 8.57.1 (solo-app)")))
         (source (anmp-write (expand-file-name "src/index.js" project)
                             "export const greet = (who) => `hi ${who}`;\n"))
         (outside (anmp-write (expand-file-name "scratch/notes.js" anmp-root)
                              "// not part of any node project\n"))
         (global-before (copy-sequence (default-value 'exec-path)))
         (observed nil))
    (setopt add-node-modules-path-command '("pnpm bin"))
    (global-set-key (kbd "C-c n") #'add-node-modules-path)
    (anmp-visit source)
    (push (list :on-arrival
                (list :mode major-mode
                      :path (anmp-exec-path-state)
                      :eslint (anmp-run "eslint")))
          observed)
    (execute-kbd-macro (kbd "C-c n"))
    (push (list :after-the-command
                (list :path (anmp-exec-path-state)
                      :eslint (anmp-run "eslint")))
          observed)
    (anmp-visit outside)
    (push (list :buffer-outside-the-project
                (list :path (anmp-exec-path-state)
                      :eslint (anmp-run "eslint")))
          observed)
    (anmp-visit source)
    (push (list :back-in-the-project
                (list :path (anmp-exec-path-state)
                      :eslint (anmp-run "eslint")))
          observed)
    (push (list :tools (anmp-tool-calls)
                :global-exec-path-unchanged
                (equal (default-value 'exec-path) global-before))
          observed)
    (nreverse observed)))"##;

    let expect = expect![[
        r#"OK ((:on-arrival (:mode js-mode :path (:buffer-local nil :added nil :global-tail-intact t) :eslint (:found nil))) (:after-the-command (:path (:buffer-local t :added ("solo-app/node_modules/.bin") :global-tail-intact t) :eslint (:found "solo-app/node_modules/.bin/eslint" :status 0 :output "eslint 8.57.1 (solo-app)"))) (:buffer-outside-the-project (:path (:buffer-local nil :added nil :global-tail-intact t) :eslint (:found nil))) (:back-in-the-project (:path (:buffer-local t :added ("solo-app/node_modules/.bin") :global-tail-intact t) :eslint (:found "solo-app/node_modules/.bin/eslint" :status 0 :output "eslint 8.57.1 (solo-app)"))) (:tools ("pnpm bin @ solo-app/src") :global-exec-path-unchanged t))"#
    ]];

    assert_add_node_modules_path_parity(elisp_form, expect);
}

/// The README's other documented usage: wire the command onto a mode hook so it
/// runs whenever a JavaScript file is opened.
///
/// The block the README prints is `(eval-after-load 'js-mode '(add-hook
/// 'js-mode-hook #'add-node-modules-path))', and it never takes effect -- js.el
/// provides the feature `js', not `js-mode', so the deferred form is filed under
/// a feature nothing ever provides and the hook stays empty.  The workflow runs
/// the documented block first and records that the project's `eslint' is still
/// unreachable, then the same wiring against the real feature name, after which
/// simply opening a project file is enough.  A JavaScript file that belongs to
/// no node project runs the hook too and correctly adds nothing: pnpm reports a
/// `node_modules/.bin' below the working directory whether or not it exists, so
/// it is the package's own `file-directory-p' check that has to reject it.
#[test]
fn the_readme_js_mode_hook_only_wires_up_under_the_feature_name_js() {
    let elisp_form = r##"(progn
  (anmp-install-tools)
  (let* ((project (anmp-project
                   "hooked-app"
                   "{\n  \"name\": \"hooked-app\",\n  \"version\": \"0.9.2\"\n}\n"
                   '("eslint" . "eslint 9.14.0 (hooked-app)")))
         (first (anmp-write (expand-file-name "src/one.js" project) "// one\n"))
         (second (anmp-write (expand-file-name "src/two.js" project) "// two\n"))
         (outside (anmp-write (expand-file-name "sketches/three.js" anmp-root)
                              "// three\n"))
         (observed nil))
    (setopt add-node-modules-path-command '("pnpm bin"))
    (eval-after-load 'js-mode
      '(add-hook 'js-mode-hook #'add-node-modules-path))
    (anmp-visit first)
    (push (list :as-the-readme-writes-it
                (list :js-mode-is-a-feature (featurep 'js-mode)
                      :js-is-a-feature (featurep 'js)
                      :js-mode-hook (copy-sequence js-mode-hook)
                      :path (anmp-exec-path-state)
                      :eslint (anmp-run "eslint")))
          observed)
    (eval-after-load 'js
      '(add-hook 'js-mode-hook #'add-node-modules-path))
    (anmp-visit second)
    (push (list :under-the-real-feature-name
                (list :js-mode-hook (copy-sequence js-mode-hook)
                      :path (anmp-exec-path-state)
                      :eslint (anmp-run "eslint")))
          observed)
    (anmp-visit outside)
    (push (list :javascript-file-in-no-project
                (list :path (anmp-exec-path-state)
                      :eslint (anmp-run "eslint")))
          observed)
    (push (list :tools (anmp-tool-calls)) observed)
    (nreverse observed)))"##;

    let expect = expect![[
        r#"OK ((:as-the-readme-writes-it (:js-mode-is-a-feature nil :js-is-a-feature t :js-mode-hook nil :path (:buffer-local nil :added nil :global-tail-intact t) :eslint (:found nil))) (:under-the-real-feature-name (:js-mode-hook (add-node-modules-path) :path (:buffer-local t :added ("hooked-app/node_modules/.bin") :global-tail-intact t) :eslint (:found "hooked-app/node_modules/.bin/eslint" :status 0 :output "eslint 9.14.0 (hooked-app)"))) (:javascript-file-in-no-project (:path (:buffer-local nil :added nil :global-tail-intact t) :eslint (:found nil))) (:tools ("pnpm bin @ hooked-app/src" "pnpm bin @ sketches")))"#
    ]];

    assert_add_node_modules_path_parity(elisp_form, expect);
}

/// The README's monorepo section, exercised as the `use-package' block it
/// documents: `:custom' sets `add-node-modules-path-command' to `("pnpm bin"
/// "pnpm bin -w")' so that both the package's own bin directory and the
/// workspace root's are picked up.
///
/// Both directories hold an `eslint', with different versions, so the order the
/// package establishes is observable rather than merely recorded: the package
/// reverses the directory list before adding, which has to leave the *nearest*
/// bin first, and it is `packages/ui''s eslint 9.17.0 that must run rather than
/// the root's 7.32.0.  `prettier' exists only at the root, so it must be
/// reachable too.  Running the command a second time invokes both tools again
/// but must not lengthen `exec-path'; and from a buffer at the workspace root
/// both commands name the same directory, which must collapse to one entry.
#[test]
fn the_readme_monorepo_use_package_block_adds_both_bins_nearest_first() {
    let elisp_form = r##"(progn
  (anmp-install-tools)
  (require 'use-package)
  (let* ((workspace (anmp-project
                     "monorepo"
                     "{\n  \"name\": \"monorepo\",\n  \"private\": true\n}\n"
                     '("eslint" . "eslint 7.32.0 (monorepo root)")
                     '("prettier" . "prettier 3.4.2 (monorepo root)")))
         (ui (anmp-project
              "monorepo/packages/ui"
              "{\n  \"name\": \"@monorepo/ui\",\n  \"version\": \"0.3.1\"\n}\n"
              '("eslint" . "eslint 9.17.0 (packages/ui)")))
         (source (anmp-write (expand-file-name "src/app.js" ui) "// app\n"))
         (release (anmp-write (expand-file-name "tools/release.js" workspace)
                              "// release\n"))
         (observed nil))
    (anmp-write (expand-file-name "pnpm-workspace.yaml" workspace)
                "packages:\n  - \"packages/*\"\n")
    (global-set-key (kbd "C-c n") #'add-node-modules-path)
    (use-package add-node-modules-path
      :custom
      (add-node-modules-path-command '("pnpm bin" "pnpm bin -w")))
    (push (list :configured add-node-modules-path-command) observed)
    (anmp-visit source)
    (execute-kbd-macro (kbd "C-c n"))
    (push (list :in-packages-ui
                (list :path (anmp-exec-path-state)
                      :eslint (anmp-run "eslint")
                      :prettier (anmp-run "prettier")))
          observed)
    (execute-kbd-macro (kbd "C-c n"))
    (push (list :command-run-a-second-time
                (list :path (anmp-exec-path-state)
                      :eslint (anmp-run "eslint")))
          observed)
    (anmp-visit release)
    (execute-kbd-macro (kbd "C-c n"))
    (push (list :in-the-workspace-root
                (list :path (anmp-exec-path-state)
                      :eslint (anmp-run "eslint")
                      :prettier (anmp-run "prettier")))
          observed)
    (push (list :tools (anmp-tool-calls)) observed)
    (nreverse observed)))"##;

    let expect = expect![[
        r#"OK ((:configured ("pnpm bin" "pnpm bin -w")) (:in-packages-ui (:path (:buffer-local t :added ("monorepo/packages/ui/node_modules/.bin" "monorepo/node_modules/.bin") :global-tail-intact t) :eslint (:found "monorepo/packages/ui/node_modules/.bin/eslint" :status 0 :output "eslint 9.17.0 (packages/ui)") :prettier (:found "monorepo/node_modules/.bin/prettier" :status 0 :output "prettier 3.4.2 (monorepo root)"))) (:command-run-a-second-time (:path (:buffer-local t :added ("monorepo/packages/ui/node_modules/.bin" "monorepo/node_modules/.bin") :global-tail-intact t) :eslint (:found "monorepo/packages/ui/node_modules/.bin/eslint" :status 0 :output "eslint 9.17.0 (packages/ui)"))) (:in-the-workspace-root (:path (:buffer-local t :added ("monorepo/node_modules/.bin") :global-tail-intact t) :eslint (:found "monorepo/node_modules/.bin/eslint" :status 0 :output "eslint 7.32.0 (monorepo root)") :prettier (:found "monorepo/node_modules/.bin/prettier" :status 0 :output "prettier 3.4.2 (monorepo root)"))) (:tools ("pnpm bin @ monorepo/packages/ui/src" "pnpm bin -w @ monorepo/packages/ui/src" "pnpm bin @ monorepo/packages/ui/src" "pnpm bin -w @ monorepo/packages/ui/src" "pnpm bin @ monorepo/tools" "pnpm bin -w @ monorepo/tools")))"#
    ]];

    assert_add_node_modules_path_parity(elisp_form, expect);
}

/// With `add-node-modules-path-debug' on, a user who has kept the package's
/// out-of-the-box `npm bin' alongside two pnpm commands is told exactly what
/// happened.  All three failure shapes carry the real tool's own words:
///
/// * `npm bin' was removed in npm 9, and npm 10.9.7 prints its multi-line
///   `Unknown command: "bin"' help text on stdout, so the package captures it
///   and quotes the whole thing back;
/// * `pnpm bin -w' outside a workspace writes to stderr, which
///   `shell-command-to-string' folds into the same stream;
/// * `pnpm bin' succeeds, and the one directory that survives is announced.
///
/// The assertion is the rendered *Warnings* buffer -- what the user reads --
/// together with the echo area line and the resulting path.
#[test]
fn debug_mode_quotes_each_tools_own_failure_output_and_names_what_it_added() {
    let elisp_form = r##"(progn
  (anmp-install-tools)
  (let* ((project (anmp-project
                   "debugged-app"
                   "{\n  \"name\": \"debugged-app\",\n  \"version\": \"3.1.0\"\n}\n"
                   '("eslint" . "eslint 8.57.1 (debugged-app)")))
         (source (anmp-write (expand-file-name "src/index.js" project) "// index\n"))
         (mark nil))
    (setopt add-node-modules-path-command '("npm bin" "pnpm bin" "pnpm bin -w")
            add-node-modules-path-debug t)
    (global-set-key (kbd "C-c n") #'add-node-modules-path)
    (anmp-visit source)
    (setq mark (anmp-echo-mark))
    (execute-kbd-macro (kbd "C-c n"))
    (list :path (anmp-exec-path-state)
          :eslint (anmp-run "eslint")
          :said (anmp-said-since mark)
          :tools (anmp-tool-calls))))"##;

    let expect = expect![[
        r#"OK (:path (:buffer-local t :added ("debugged-app/node_modules/.bin") :global-tail-intact t) :eslint (:found "debugged-app/node_modules/.bin/eslint" :status 0 :output "eslint 8.57.1 (debugged-app)") :said (:messages ("Added to ‘exec-path‘: [ORACLE-SANDBOX]/debugged-app/node_modules/.bin" "Warning (add-node-modules-path): Failed to run ‘npm bin’:" " Unknown command: \"bin\"" "To see a list of supported npm commands, run:" "  npm help" "Warning (add-node-modules-path): Failed to run ‘pnpm bin -w’:" " [ERROR] --workspace-root may only be used inside a workspace") :warnings "Warning (add-node-modules-path): Failed to run ‘npm bin’:\n Unknown command: \"bin\"\n\nTo see a list of supported npm commands, run:\n  npm help\nWarning (add-node-modules-path): Failed to run ‘pnpm bin -w’:\n [ERROR] --workspace-root may only be used inside a workspace\n") :tools ("npm bin @ debugged-app/src" "pnpm bin @ debugged-app/src" "pnpm bin -w @ debugged-app/src"))"#
    ]];

    assert_add_node_modules_path_parity(elisp_form, expect);
}

/// The same three commands with debugging left at its default: the successful
/// directory is still added, and nothing at all is said -- no echo area line,
/// and no *Warnings* buffer is ever created.
///
/// Then the two ways a node project can have no usable bin directory, each
/// failing for a different reason so that a check on the wrong predicate would
/// show: a project whose dependencies installed no executables, where
/// `node_modules' exists but `node_modules/.bin' does not, and a half-extracted
/// install where `node_modules/.bin' exists as a regular file.  In both the
/// package must leave `exec-path' alone -- not merely add nothing, but never
/// make the variable buffer local at all.
#[test]
fn without_debug_nothing_is_reported_and_an_unusable_bin_leaves_exec_path_global() {
    let elisp_form = r##"(progn
  (anmp-install-tools)
  (let* ((working (anmp-project
                   "quiet-app"
                   "{\n  \"name\": \"quiet-app\",\n  \"version\": \"1.0.0\"\n}\n"
                   '("eslint" . "eslint 8.57.1 (quiet-app)")))
         (working-source (anmp-write (expand-file-name "src/index.js" working)
                                     "// index\n"))
         (bare (anmp-project "bare-app" "{\n  \"name\": \"bare-app\"\n}\n"))
         (bare-source (anmp-write (expand-file-name "src/index.js" bare)
                                  "// index\n"))
         (packed (anmp-project "packed-app" "{\n  \"name\": \"packed-app\"\n}\n"))
         (packed-source (anmp-write (expand-file-name "src/index.js" packed)
                                    "// index\n"))
         (observed nil)
         (mark nil))
    (make-directory (expand-file-name "node_modules" bare) t)
    (anmp-write (expand-file-name "node_modules/.bin" packed)
                "this install left a file where the bin directory belongs\n")
    (setopt add-node-modules-path-command '("npm bin" "pnpm bin" "pnpm bin -w"))
    (global-set-key (kbd "C-c n") #'add-node-modules-path)
    (dolist (case (list (cons :a-working-project working-source)
                        (cons :dependencies-installed-no-binaries bare-source)
                        (cons :bin-is-a-regular-file packed-source)))
      (anmp-visit (cdr case))
      (setq mark (anmp-echo-mark))
      (execute-kbd-macro (kbd "C-c n"))
      (push (list (car case)
                  (list :path (anmp-exec-path-state)
                        :eslint (anmp-run "eslint")
                        :said (anmp-said-since mark)))
            observed))
    (push (list :tools (anmp-tool-calls)) observed)
    (nreverse observed)))"##;

    let expect = expect![[
        r#"OK ((:a-working-project (:path (:buffer-local t :added ("quiet-app/node_modules/.bin") :global-tail-intact t) :eslint (:found "quiet-app/node_modules/.bin/eslint" :status 0 :output "eslint 8.57.1 (quiet-app)") :said (:messages nil :warnings ""))) (:dependencies-installed-no-binaries (:path (:buffer-local nil :added nil :global-tail-intact t) :eslint (:found nil) :said (:messages nil :warnings ""))) (:bin-is-a-regular-file (:path (:buffer-local nil :added nil :global-tail-intact t) :eslint (:found nil) :said (:messages nil :warnings ""))) (:tools ("npm bin @ quiet-app/src" "pnpm bin @ quiet-app/src" "pnpm bin -w @ quiet-app/src" "npm bin @ bare-app/src" "pnpm bin @ bare-app/src" "pnpm bin -w @ bare-app/src" "npm bin @ packed-app/src" "pnpm bin @ packed-app/src" "pnpm bin -w @ packed-app/src")))"#
    ]];

    assert_add_node_modules_path_parity(elisp_form, expect);
}

