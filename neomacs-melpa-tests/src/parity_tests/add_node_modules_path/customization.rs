#[test]
fn add_node_modules_path_command_custom_setter_normalizes_every_non_list_value() {
    let elisp_form = r##"(let ((setter
                (get
                 'add-node-modules-path-command
                 'custom-set))
               results)
         (dolist (value
                  '("npm bin"
                    command-symbol
                    42
                    nil
                    [one two]
                    (one two)
                    ("pnpm bin" "pnpm bin -w")))
           (makunbound
            'add-node-modules-path--setter-target)
           (funcall
            setter
            'add-node-modules-path--setter-target
            value)
           (push
            (list
             value
             (default-boundp
              'add-node-modules-path--setter-target)
             (default-value
              'add-node-modules-path--setter-target))
            results))
         (nreverse
          results))"##;
    let expect = expect![[
        r#"OK (("npm bin" t ("npm bin")) (command-symbol t (command-symbol)) (42 t (42)) (nil t nil) (#1=[one two] t (#1#)) (#2=(one two) t #2#) (#3=("pnpm bin" "pnpm bin -w") t #3#))"#
    ]];
    assert_add_node_modules_path_parity(elisp_form, expect);
}

#[test]
fn add_node_modules_path_command_custom_setter_preserves_list_identity() {
    let elisp_form = r##"(let* ((setter
                  (get
                   'add-node-modules-path-command
                   'custom-set))
                 (proper
                  (list
                   "one"
                   "two"))
                 (empty nil))
         (funcall
          setter
          'add-node-modules-path--proper-target
          proper)
         (funcall
          setter
          'add-node-modules-path--empty-target
          empty)
         (list
          (eq
           proper
           (default-value
            'add-node-modules-path--proper-target))
          (default-value
           'add-node-modules-path--proper-target)
          (eq
           empty
           (default-value
            'add-node-modules-path--empty-target))
          (default-value
           'add-node-modules-path--empty-target)))"##;
    let expect = expect![[r#"OK (t ("one" "two") t nil)"#]];
    assert_add_node_modules_path_parity(elisp_form, expect);
}
