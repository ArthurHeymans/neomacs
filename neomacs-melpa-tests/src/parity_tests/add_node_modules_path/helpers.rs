#[test]
fn add_node_modules_path_trim_covers_whitespace_empty_nonstrings_and_nonlists() {
    let elisp_form = r##"(list
         (add-node-modules-path/trim-list-and-elements
          '(" npm bin "
            "\tpnpm bin -w\n"
            ""
            " \t\n "
            nil
            42
            command
            "node_modules/.bin"))
         (add-node-modules-path/trim-list-and-elements
          nil)
         (add-node-modules-path/trim-list-and-elements
          "npm bin")
         (add-node-modules-path/trim-list-and-elements
          42)
         (add-node-modules-path/trim-list-and-elements
          [one two])
         (condition-case error-data
             (add-node-modules-path/trim-list-and-elements
              '(one . two))
           (error
            (list
             'signal
             (car
              error-data)
             (cdr
              error-data)))))"##;
    let expect = expect![[
        r#"OK (("npm bin" "pnpm bin -w" "node_modules/.bin") nil nil nil nil (signal wrong-type-argument (listp two)))"#
    ]];
    assert_add_node_modules_path_parity(elisp_form, expect);
}

