        r#"OK (((command "valid" result "/workspace/node_modules/.bin" directory-p t) (command "multiline" result "first\nsecond\n" directory-p nil) (command "spaced" result "  spaced path  " directory-p nil)) ("valid" "multiline" "spaced") ("/workspace/node_modules/.bin" "first\nsecond\n" "  spaced path  "))"#
